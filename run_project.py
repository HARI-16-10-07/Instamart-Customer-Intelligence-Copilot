"""
Instamart Customer Intelligence & Support Copilot
Master runner for a full rebuild from the existing raw CSV and policy files.

Run from the project root:
    python run_project.py

Important:
- Does NOT regenerate synthetic raw data (does not run generate_data.py).
- Rebuilds cleaned data, SQLite database, ML outputs, ticket triage and Part D outputs.
- Before running the refund-agent demo, backs up existing agent JSONL ledgers and
  the complete state/ checkpoint folder into backups/full_rebuild_<timestamp>/.
- Existing agent history/checkpoints are preserved in that backup; new agent
  demo records are appended/generated by the existing Part D script.
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor, as_completed
from datetime import datetime
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SRC = ROOT / "src"
DATA = ROOT / "data"
RAW = DATA / "raw"
POLICIES = DATA / "policies"
OUTPUTS = ROOT / "outputs"
STATE = ROOT / "state"
BACKUPS = ROOT / "backups"


def print_header(title: str) -> None:
    print("\n" + "=" * 78)
    print(title)
    print("=" * 78, flush=True)


def require_files(paths: list[Path]) -> None:
    missing = [str(path.relative_to(ROOT)) for path in paths if not path.is_file()]
    if missing:
        raise FileNotFoundError(
            "Required input files are missing:\n  - " + "\n  - ".join(missing)
        )


def run_script(script_name: str) -> None:
    """Run one project script using the current virtual-environment Python."""
    script_path = SRC / script_name
    if not script_path.is_file():
        raise FileNotFoundError(f"Project script not found: {script_path}")

    print_header(f"RUNNING: src/{script_name}")
    subprocess.run(
        [sys.executable, str(script_path)],
        cwd=ROOT,
        check=True,
    )
    print(f"\nCOMPLETED: src/{script_name}", flush=True)


def backup_agent_files() -> Path:
    """
    Preserve agent history and checkpoints before the agent demo can append
    ledger records or create/overwrite checkpoint files.
    """
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    backup_dir = BACKUPS / f"full_rebuild_{timestamp}"
    backup_dir.mkdir(parents=True, exist_ok=False)

    files_to_backup = [
        OUTPUTS / "agent_runs.jsonl",
        OUTPUTS / "refund_ledger.jsonl",
    ]

    for source in files_to_backup:
        if source.exists():
            shutil.copy2(source, backup_dir / source.name)
            print(f"Backed up: {source.relative_to(ROOT)}")

    if STATE.exists():
        shutil.copytree(STATE, backup_dir / "state")
        print(f"Backed up: state/ ({sum(1 for p in STATE.rglob('*') if p.is_file())} files)")
    else:
        print("No existing state/ folder found; nothing to back up.")

    print(f"Agent backup location: {backup_dir.relative_to(ROOT)}")
    return backup_dir


def run_parallel_stage(script_names: list[str]) -> None:
    """Run scripts concurrently only when they have independent inputs/outputs."""
    print_header("RUNNING INDEPENDENT TASKS IN PARALLEL")
    failures: list[tuple[str, Exception]] = []

    with ThreadPoolExecutor(max_workers=len(script_names)) as executor:
        futures = {
            executor.submit(run_script, script_name): script_name
            for script_name in script_names
        }
        for future in as_completed(futures):
            script_name = futures[future]
            try:
                future.result()
            except Exception as exc:
                failures.append((script_name, exc))

    if failures:
        details = "\n".join(
            f"  - {name}: {error}" for name, error in failures
        )
        raise RuntimeError("One or more parallel tasks failed:\n" + details)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Run the complete Instamart project pipeline from existing raw data."
    )
    parser.add_argument(
        "--skip-agent",
        action="store_true",
        help="Skip the refund-agent scenario/demo run (no agent ledger or checkpoint changes).",
    )
    args = parser.parse_args()

    required_inputs = [
        RAW / "customers.csv",
        RAW / "orders.csv",
        RAW / "products.csv",
        RAW / "tickets.csv",
        RAW / "agent_scenarios.csv",
        RAW / "policy_eval.csv",
        POLICIES / "delivery_policy.txt",
        POLICIES / "escalation_policy.txt",
        POLICIES / "payment_policy.txt",
        POLICIES / "privacy_policy.txt",
        POLICIES / "refund_policy.txt",
    ]

    print_header("INSTAMART CUSTOMER INTELLIGENCE & SUPPORT COPILOT")
    print("Mode: FULL REBUILD FROM EXISTING RAW DATA")
    print("Raw data generation: SKIPPED (generate_data.py will not be run)")
    print(f"Python: {sys.executable}")
    print(f"Project: {ROOT}")

    require_files(required_inputs)
    OUTPUTS.mkdir(parents=True, exist_ok=True)

    # PART A: audit raw files, clean them, and rebuild the existing SQLite DB.
    print_header("PART A — DATA FOUNDATION")
    run_script("audit_raw_data.py")
    run_script("clean_data.py")
    run_script("create_database.py")

    # PART B prerequisites and Part D policy preparation read independent inputs.
    # The two Part B data-preparation scripts both read the rebuilt DB but write
    # different outputs; policy RAG and SQL analysis are also independent here.
    run_parallel_stage([
        "prepare_lapse_data.py",
        "build_customer_segments.py",
        "policy_rag.py",
        "run_sql_analysis.py",
    ])

    # Finish Part B in dependency order.
    print_header("PART B — CUSTOMER INTELLIGENCE")
    run_script("train_lapse_models.py")
    run_script("create_retention_list.py")

    # PART C consumes the customer-segment output created in Part B.
    print_header("PART C — SUPPORT TICKET TRIAGE")
    run_script("triage_tickets.py")

    # Part D tool checks are run after policy retrieval has been prepared.
    print_header("PART D — POLICY ASSISTANT AND REFUND AGENT")
    run_script("refund_tools.py")

    if args.skip_agent:
        print("\nAgent scenarios skipped by request. Existing ledgers/checkpoints were not changed.")
    else:
        print_header("BACKUP BEFORE REFUND-AGENT DEMONSTRATIONS")
        backup_agent_files()
        run_script("refund_agent.py")

    print_header("PROJECT PIPELINE FINISHED")
    print("All selected stages completed successfully.")
    print("Review generated files in outputs/ and the rebuilt database at data/instamart.db.")
    if not args.skip_agent:
        print("Previous agent ledgers/checkpoints are preserved under backups/full_rebuild_*/.")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except subprocess.CalledProcessError as exc:
        print(
            f"\nPIPELINE STOPPED: {exc.cmd} exited with code {exc.returncode}.",
            file=sys.stderr,
        )
        raise SystemExit(exc.returncode)
    except Exception as exc:
        print(f"\nPIPELINE STOPPED: {exc}", file=sys.stderr)
        raise SystemExit(1)
